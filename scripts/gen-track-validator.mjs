#!/usr/bin/env node
// Compiles schema/track.schema.json into a standalone validator module (src/domain/generated/).
// Ajv's runtime compiler uses `new Function`, which the Content Security Policy forbids (SEC-1), so
// the browser and the server run this pre-generated code instead. The output is committed;
// src/domain/generated/trackSchemaValidator.test.ts fails when it is out of date with the schema.
//
// Usage: npm run gen:schema           (writes the file)
//        node scripts/gen-track-validator.mjs --print   (prints it, for the drift check)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'src/domain/generated/trackSchemaValidator.js');
const require = createRequire(import.meta.url);

export function generate() {
  const schema = JSON.parse(readFileSync(join(ROOT, 'schema/track.schema.json'), 'utf8'));
  const is2020 = typeof schema.$schema === 'string' && schema.$schema.includes('2020-12');
  const AjvClass = is2020 ? require('ajv/dist/2020').default : require('ajv').default;
  const standaloneCode = require('ajv/dist/standalone').default;
  const ajv = new AjvClass({ code: { source: true, esm: true }, strict: false, allErrors: true, validateFormats: false });
  let code = standaloneCode(ajv, ajv.compile(schema));
  // Standalone output may require() runtime helpers; turn those into ESM imports.
  const imports = [];
  code = code.replace(/require\("([^"]+)"\)/g, (_m, spec) => {
    const i = imports.length;
    const path = spec.endsWith('.js') ? spec : `${spec}.js`;
    imports.push(`import __ns${i} from ${JSON.stringify(path)};\nconst __ajvRuntime${i} = { default: __pick(__ns${i}) };`);
    return `__ajvRuntime${i}`;
  });
  const pick = 'const __pick = (m) => { const d = m && m.default !== undefined ? m.default : m; return d && typeof d === "object" && "default" in d ? d.default : d; };';
  const header = '// GENERATED by scripts/gen-track-validator.mjs from schema/track.schema.json. Do not edit; run `npm run gen:schema`.\n/* eslint-disable */\n// @ts-nocheck\n';
  return header + (imports.length ? pick + '\n' + imports.join('\n') + '\n' : '') + code + '\n';
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const code = generate();
  if (process.argv.includes('--print')) process.stdout.write(code);
  else {
    writeFileSync(OUT, code);
    console.log(`Wrote ${OUT.slice(ROOT.length + 1)}`);
  }
}
